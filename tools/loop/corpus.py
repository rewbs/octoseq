#!/usr/bin/env python3
"""The tracker-module corpus for the analysis-accuracy loop.

    python3 tools/loop/corpus.py list
    python3 tools/loop/corpus.py restore               # download the modules listed in the manifest
    python3 tools/loop/corpus.py fetch --limit 24      # add more public-domain modules to the manifest
    python3 tools/loop/corpus.py fixtures              # rewrite the committed fixtures

Three sources, each split into a training half and a held-out half:

- synthetic: generated by modgen.py from a seed. Nothing third-party in them. A few
  are committed under fixtures/modules/ as regression fixtures; the rest are
  generated into the cache on demand.
- downloaded: modules The Mod Archive lists under its Public Domain licence. Files
  go to a git-ignored cache and are never committed; corpus/manifest.json records
  each one's source page, stated licence and checksum.
- local: any modules dropped into .loop/modules/train or .loop/modules/heldout
  (for example songs exported from ScreamSeq). Never committed.

The split of a module never changes: synthetic by seed range, downloaded by the
manifest, local by directory. Held-out modules must not be used for tuning.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import modgen  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).parent
CACHE = ROOT / ".loop" / "cache" / "modules"
LOCAL = ROOT / ".loop" / "modules"
FIXTURES = HERE / "fixtures" / "modules"
FIXTURE_INDEX = HERE / "fixtures" / "fixtures.json"
MANIFEST = HERE / "corpus" / "manifest.json"

SYNTH_SEEDS = {"train": range(1, 13), "heldout": range(101, 113)}
FIXTURE_SEEDS = [1, 2, 101, 102]
MODULE_SUFFIXES = {".mod", ".xm", ".s3m", ".it", ".mptm"}
MAX_DOWNLOAD_BYTES = 3_000_000
USER_AGENT = "octoseq-loop/0.1 (analysis accuracy test corpus)"
LISTING = "https://modarchive.org/index.php?request=view_by_license&query=publicdomain&page={page}"
MODULE_PAGE = "https://modarchive.org/index.php?request=view_by_moduleid&query={id}"
DOWNLOAD = "https://api.modarchive.org/downloads.php?moduleid={id}"
ALLOWED_LICENCES = {"Public Domain"}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def synthetic(split: str) -> list[dict]:
    out = []
    directory = CACHE / "synth"
    directory.mkdir(parents=True, exist_ok=True)
    for seed in SYNTH_SEEDS[split]:
        path = directory / f"synth-{seed:04d}.mod"
        truth_path = path.with_suffix(".truth.json")
        if not path.exists() or not truth_path.exists():
            data, truth = modgen.generate(seed)
            path.write_bytes(data)
            truth_path.write_text(json.dumps(truth, separators=(",", ":")))
        out.append(dict(id=path.stem, path=path, split=split, source="synthetic", truth=truth_path))
    return out


def downloaded(split: str) -> list[dict]:
    if not MANIFEST.exists():
        return []
    out = []
    for entry in json.loads(MANIFEST.read_text())["modules"]:
        path = CACHE / "modarchive" / entry["file"]
        if entry["split"] == split and path.exists() and sha256(path.read_bytes()) == entry["sha256"]:
            out.append(dict(id=f"ma-{entry['id']}", path=path, split=split, source="downloaded", truth=None))
    return out


def local(split: str) -> list[dict]:
    directory = LOCAL / split
    if not directory.exists():
        return []
    return [
        dict(id=f"local-{p.stem}", path=p, split=split, source="local", truth=None)
        for p in sorted(directory.iterdir())
        if p.suffix.lower() in MODULE_SUFFIXES
    ]


def load(split: str, sources: tuple[str, ...] = ("synthetic", "downloaded", "local")) -> list[dict]:
    loaders = {"synthetic": synthetic, "downloaded": downloaded, "local": local}
    return [item for source in sources for item in loaders[source](split)]


# ----------------------------------------------------------------------- fixtures


def write_fixtures() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    index = {
        "licence": "Generated by tools/loop/modgen.py; no third-party content. Covered by this repository's licence.",
        "modules": [],
    }
    for seed in FIXTURE_SEEDS:
        data, truth = modgen.generate(seed)
        name = f"synth-{seed:04d}.mod"
        (FIXTURES / name).write_bytes(data)
        index["modules"].append(dict(file=name, seed=seed, sha256=sha256(data), triggers=len(truth["triggers"]), bpm=truth["bpm"]))
    FIXTURE_INDEX.write_text(json.dumps(index, indent=2) + "\n")
    print(f"wrote {len(FIXTURE_SEEDS)} fixtures to {FIXTURES.relative_to(ROOT)}")


def check_fixtures() -> list[str]:
    """Problems with the committed fixtures: missing, altered, or no longer reproducible."""
    problems = []
    index = json.loads(FIXTURE_INDEX.read_text())
    for entry in index["modules"]:
        path = FIXTURES / entry["file"]
        if not path.exists():
            problems.append(f"{entry['file']} is missing")
            continue
        if sha256(path.read_bytes()) != entry["sha256"]:
            problems.append(f"{entry['file']} does not match its recorded checksum")
        if sha256(modgen.generate(entry["seed"])[0]) != entry["sha256"]:
            problems.append(f"modgen no longer reproduces {entry['file']} from seed {entry['seed']}")
    return problems


# ----------------------------------------------------------------------- download


def _get(url: str, limit: int) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = response.read(limit + 1)
    if len(data) > limit:
        raise ValueError("response larger than the size limit")
    return data


def fetch(limit: int, first_page: int) -> None:
    """Download public-domain modules, verifying the licence on each module's own page."""
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {"modules": []}
    known = {m["id"] for m in manifest["modules"]}
    target = CACHE / "modarchive"
    target.mkdir(parents=True, exist_ok=True)
    added, page = 0, first_page
    while added < limit and page < first_page + 10:
        listing = _get(LISTING.format(page=page), 2_000_000).decode("utf-8", "replace")
        candidates = re.findall(r'downloads\.php\?moduleid=(\d+)#([A-Za-z0-9_.!+\-]+)["\']', listing)
        if not candidates:
            break
        for module_id, filename in dict(candidates).items():
            if added >= limit:
                break
            if module_id in known or Path(filename).suffix.lower() not in MODULE_SUFFIXES - {".mptm"}:
                continue
            time.sleep(1.0)  # be a polite client
            try:
                page_html = _get(MODULE_PAGE.format(id=module_id), 2_000_000).decode("utf-8", "replace")
                licence = re.search(r'Licensed under the <a[^>]*href="([^"]+)"[^>]*>([^<]+?) license</a>', page_html)
                if not licence or licence.group(2).strip() not in ALLOWED_LICENCES:
                    continue
                time.sleep(1.0)
                data = _get(DOWNLOAD.format(id=module_id), MAX_DOWNLOAD_BYTES)
            except Exception as error:  # noqa: BLE001 - skip anything that does not download cleanly
                print(f"skip {module_id}: {error}")
                continue
            safe = f"{module_id}{Path(filename).suffix.lower()}"
            (target / safe).write_bytes(data)
            digest = sha256(data)
            manifest["modules"].append(dict(
                id=module_id, file=safe, original_name=filename, sha256=digest, bytes=len(data),
                source=MODULE_PAGE.format(id=module_id), download=DOWNLOAD.format(id=module_id),
                licence=licence.group(2).strip(), licence_url=licence.group(1),
                licence_basis="stated on the module's page at The Mod Archive when fetched",
                split="heldout" if int(digest[:8], 16) % 2 else "train",
            ))  # fmt: skip
            known.add(module_id)
            added += 1
            print(f"fetched {module_id} {filename} ({len(data)} bytes)")
        page += 1
    manifest["modules"].sort(key=lambda m: int(m["id"]))
    manifest["note"] = "Files are downloaded to a git-ignored cache and are not redistributed in this repository."
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"{added} added; manifest has {len(manifest['modules'])} modules")


def restore() -> None:
    """Re-download every module in the manifest that is missing from the cache, checking checksums."""
    if not MANIFEST.exists():
        print("no manifest")
        return
    target = CACHE / "modarchive"
    target.mkdir(parents=True, exist_ok=True)
    restored = present = failed = 0
    for entry in json.loads(MANIFEST.read_text())["modules"]:
        path = target / entry["file"]
        if path.exists() and sha256(path.read_bytes()) == entry["sha256"]:
            present += 1
            continue
        time.sleep(1.0)
        try:
            data = _get(entry["download"], MAX_DOWNLOAD_BYTES)
        except Exception as error:  # noqa: BLE001
            print(f"could not fetch {entry['id']}: {error}")
            failed += 1
            continue
        if sha256(data) != entry["sha256"]:
            print(f"{entry['id']} no longer matches its recorded checksum; left out")
            failed += 1
            continue
        path.write_bytes(data)
        restored += 1
    print(f"{present} already present, {restored} restored, {failed} unavailable")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list")
    sub.add_parser("fixtures")
    sub.add_parser("restore")
    fetch_parser = sub.add_parser("fetch")
    fetch_parser.add_argument("--limit", type=int, default=24)
    fetch_parser.add_argument("--first-page", type=int, default=1)
    args = parser.parse_args()
    if args.command == "fixtures":
        write_fixtures()
    elif args.command == "restore":
        restore()
    elif args.command == "fetch":
        fetch(args.limit, args.first_page)
    else:
        for split in ("train", "heldout"):
            items = load(split)
            counts = {s: sum(i["source"] == s for i in items) for s in ("synthetic", "downloaded", "local")}
            print(f"{split}: {len(items)} modules {counts}")


if __name__ == "__main__":
    main()
